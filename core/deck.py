"""Deck building: digest dict → branded .pptx bytes (python-pptx).

Slides are drawn on blank layouts so the output is identical for any template;
the template supplies slide size/theme and can be swapped per client via
PPTX_TEMPLATE. `ensure_template` generates the stock 16:9 template.
"""
from __future__ import annotations

import io
import os

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.util import Emu, Inches, Pt

BRAND = RGBColor(0x0B, 0x5C, 0x8A)
INK = RGBColor(0x16, 0x32, 0x4A)
MUTED = RGBColor(0x66, 0x73, 0x80)
DEFAULT_TEMPLATE = os.environ.get("PPTX_TEMPLATE", "templates/engineering.pptx")


def ensure_template(path: str) -> str:
    """Create a blank 16:9 template if missing (also the rebranding entry point)."""
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        prs = _widescreen(Presentation())
        prs.save(path)
    return path


def build_deck(digest: dict, template_path: str | None = None) -> bytes:
    path = template_path or DEFAULT_TEMPLATE
    prs = Presentation(path if template_path else ensure_template(path))
    _widescreen(prs)
    blank = prs.slide_layouts[6]

    slide = prs.slides.add_slide(blank)
    _bar(slide, prs)
    _text(slide, Inches(0.8), Inches(2.2), Inches(11.7), Inches(1.6), digest["title"], size=40, bold=True, color=INK)
    _text(slide, Inches(0.8), Inches(3.9), Inches(11.7), Inches(0.6),
          f"{digest['period']} · generated by Digest Studio", size=18, color=MUTED)

    for section in digest["sections"]:
        slide = prs.slides.add_slide(blank)
        _bar(slide, prs)
        _text(slide, Inches(0.8), Inches(0.5), Inches(11.7), Inches(0.9), section["heading"], size=30, bold=True, color=BRAND)
        body = slide.shapes.add_textbox(Inches(0.9), Inches(1.6), Inches(11.5), Inches(5.2)).text_frame
        body.word_wrap = True
        for i, bullet in enumerate(section["bullets"]):
            para = body.paragraphs[0] if i == 0 else body.add_paragraph()
            para.text = f"• {bullet}"
            para.font.size = Pt(18)
            para.font.color.rgb = INK
            para.space_after = Pt(10)

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


def _widescreen(prs: Presentation) -> Presentation:
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    return prs


def _bar(slide, prs) -> None:
    """Thin brand bar across the top of every slide."""
    shape = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Emu(0), Emu(0), prs.slide_width, Inches(0.16))
    shape.fill.solid()
    shape.fill.fore_color.rgb = BRAND
    shape.line.fill.background()


def _text(slide, left, top, width, height, value, size, bold=False, color=INK):
    frame = slide.shapes.add_textbox(left, top, width, height).text_frame
    frame.word_wrap = True
    para = frame.paragraphs[0]
    para.text = value
    para.font.size = Pt(size)
    para.font.bold = bold
    para.font.color.rgb = color
    return frame
